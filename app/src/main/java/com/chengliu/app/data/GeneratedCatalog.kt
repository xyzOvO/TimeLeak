    fun lookup(domain: String): ServiceInfo? {
        var cursor = domain.trim().trimEnd('.').lowercase()
        while (cursor.isNotEmpty()) {
            index[cursor]?.let { return it }
            val dot = cursor.indexOf('.')
            if (dot < 0) return null
            cursor = cursor.substring(dot + 1)
        }
        return null
    }

